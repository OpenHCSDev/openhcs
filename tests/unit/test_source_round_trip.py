"""Saved Python source loads back as the value that was saved.

Pipelines and configs persist as Python source generated by pycodify, so every
formatter gap is a data-loss bug. This test generates every registered config
dataclass (lazy and base) with every field set to a non-default value derived
from its annotation, and every function-pattern shape the step editor produces
inside a pipeline document, writes them as source, loads the source back and
compares the raw values.
"""

