STEP_PARAMETERS = ("func",) + tuple(
    name for name in inspect.signature(AbstractStep.__init__).parameters if name != "self"
)


def configurable_function(image, threshold: int = 3, enabled: bool = True):
    return image


def template_function(image, *, template_path: PlateInputFile):
    return image


PATTERNS = {
    "callable": count_cells_simple,
    "callable_with_kwargs": (configurable_function, {"threshold": 9, "enabled": False}),
    "declared_path_kwarg": (
        template_function,
        {"template_path": ROOT / "templates" / "fiducial.png"},
    ),
    "nested_enum_kwargs": (
        crop,
        {"crop_shape": CropModule.Shape.ELLIPSE, "removal_method": CropModule.RemovalMethod.ALL},
    ),
    "hidden_runtime_kwargs": (measure_object_size_shape, {"calculate_zernikes": False}),
    "chain": [count_cells_simple, (configurable_function, {"threshold": 4})],
    "by_group": {
        "1": count_cells_simple,
        "2": [(configurable_function, {"threshold": 5}), count_cells_simple],
    },
}


@pytest.fixture
def declared_function_catalog(monkeypatch):
    """Registry metadata for the pattern functions, without a catalog subprocess."""

    metadata = (
        RegistryService.declared_metadata_for_callable(func)
        for func in (count_cells_simple, crop, measure_object_size_shape)
    )
    monkeypatch.setattr(RegistryService, "_metadata_cache", dict(metadata))


def step_sample(func, samples: SampleValues) -> FunctionStep:
    hints = typing.get_type_hints(AbstractStep.__init__, globalns=vars(inspect.getmodule(AbstractStep)))
    kwargs: dict = {"func": func, "name": "step", "description": "described", "enabled": False}
    for name, parameter in inspect.signature(AbstractStep.__init__).parameters.items():
        annotation = hints.get(name)
        if name in kwargs or name == "self" or annotation is None:
            continue
        config_type = typing.get_args(annotation)[0] if typing.get_origin(annotation) else annotation
        if isinstance(config_type, type) and is_dataclass(config_type):
            kwargs[name] = config_sample(config_type, samples)
        else:
            kwargs[name] = next(samples.candidates(annotation, parameter.default, name, 0))
    return FunctionStep(**kwargs)


@pytest.mark.usefixtures("declared_function_catalog")
@pytest.mark.parametrize("clean_mode", (True, False), ids=("clean", "full"))
def test_pipeline_document_loads_back_every_pattern_shape(clean_mode):
    samples = SampleValues()
    document = PipelineDocumentCodec.from_values(
        pipeline_config=config_sample(PipelineConfig, samples),
        pipeline_steps=[step_sample(pattern, samples) for pattern in PATTERNS.values()],
    )
    source = PipelineDocumentCodec.render(document, clean_mode=clean_mode)
    loaded = PipelineDocumentCodec.from_source(source)

    assert raw(loaded.pipeline_config) == raw(document.pipeline_config), source
    assert raw(loaded.pipeline_steps) == raw(document.pipeline_steps), source
    assert samples.unsampled == []
    assert "path_root = Path('/data/screen')" in source
    assert "CropModule.Shape.ELLIPSE" in source


@pytest.mark.usefixtures("declared_function_catalog")
def test_declared_path_kwarg_written_as_string_loads_back_as_path():
    path = ROOT / "templates" / "fiducial.png"
    document = PipelineDocumentCodec.from_values(
        pipeline_config=PipelineConfig(),
        pipeline_steps=[FunctionStep(func=(template_function, {"template_path": str(path)}))],
    )
    loaded = PipelineDocumentCodec.from_source(PipelineDocumentCodec.render(document))
    assert loaded.pipeline_steps[0].func[1] == {"template_path": path}
