CONFIG_TYPES = tuple(
    config_type
    for pair in LazyDataclassFactory.registered_type_pairs()
    for config_type in pair
    if not inspect.isabstract(config_type)
)


def config_sample(config_type: type, samples: SampleValues):
    hints = typing.get_type_hints(config_type)
    kwargs: dict = {}
    for declared in fields(config_type):
        if not declared.init:
            continue
        trial = samples.accepted(
            config_type, kwargs, declared.name, hints[declared.name],
            _field_default(declared), f"{config_type.__qualname__}.{declared.name}", 0,
        )
        if trial is None:
            samples.unsampled.append(f"{config_type.__qualname__}.{declared.name}")
            continue
        kwargs = trial
    return config_type(**kwargs)


@pytest.mark.parametrize("clean_mode", (True, False), ids=("clean", "full"))
@pytest.mark.parametrize("config_type", CONFIG_TYPES, ids=lambda t: t.__qualname__)
def test_every_config_loads_back_with_every_field_set(config_type, clean_mode):
    samples = SampleValues()
    value = config_sample(config_type, samples)
    source, loaded = load(value, clean_mode)
    assert raw(loaded) == raw(value), source
    assert samples.unsampled == []


@pytest.mark.parametrize("clean_mode", (True, False), ids=("clean", "full"))
@pytest.mark.parametrize("config_type", CONFIG_TYPES, ids=lambda t: t.__qualname__)
def test_every_default_config_loads_back(config_type, clean_mode):
    value = config_type()
    source, loaded = load(value, clean_mode)
    assert raw(loaded) == raw(value), source


