# ---------------------------------------------------------------------------
# Values derived from annotations
# ---------------------------------------------------------------------------


class SampleValues:
    """Candidate values of each annotation that differ from a given default.

    The first candidate the owning dataclass accepts is used, so validation
    rules (a regex that needs a named group, an axis that cannot vary) pick
    the next candidate instead of losing the field.
    """

    def __init__(self) -> None:
        self.unsampled: list[str] = []

    def candidates(self, annotation, default, label: str, depth: int) -> Iterator[object]:
        origin = typing.get_origin(annotation)
        args = typing.get_args(annotation)
        if origin is typing.Annotated:
            yield from self.candidates(args[0], default, label, depth)
        elif origin in (typing.Union, types.UnionType):
            for arg in args:
                if arg is not type(None):
                    yield from self.candidates(arg, default, label, depth)
        elif origin is typing.Literal:
            yield from (arg for arg in args if arg != default)
        elif origin is type:
            yield from self.subclasses(args[0], default)
        elif origin in (list, tuple):
            for item in itertools.islice(self.candidates(args[0], None, label, depth + 1), 4):
                yield origin((item,))
        elif origin in (dict, Mapping):
            keys = self.candidates(args[0], None, label, depth + 1)
            items = self.candidates(args[1], None, label, depth + 1)
            for key, item in itertools.islice(zip(keys, items), 4):
                yield {key: item}
        elif annotation is bool:
            yield not default if isinstance(default, bool) else True
        elif annotation is int:
            yield default + 1 if isinstance(default, int) else 7
        elif annotation is float:
            yield default + 0.5 if isinstance(default, float) else 2.5
        elif annotation is str:
            yield f"{default}_x" if isinstance(default, str) else "sample"
            yield r"(?P<sample>\w+)"
        elif annotation is Path:
            yield ROOT / label.replace(".", "_")
        elif isinstance(annotation, type) and issubclass(annotation, enum.Enum):
            yield from (member for member in reversed(annotation) if member != default)
        elif isinstance(annotation, type) and is_dataclass(annotation) and depth < 3:
            instance = self.instance(annotation, label, depth + 1)
            if instance is not _NO_SAMPLE:
                yield instance

    @staticmethod
    def subclasses(base: type, default: object) -> Iterator[type]:
        if base is object:
            yield int
            return
        for candidate in reversed([base, *_all_subclasses(base)]):
            if candidate is default or "<locals>" in candidate.__qualname__:
                continue
            if inspect.isabstract(candidate) or candidate.__module__.startswith("tests"):
                continue
            yield candidate

    def accepted(self, owner: type, kwargs: dict, name: str, annotation, default, label, depth):
        for sample in itertools.islice(self.candidates(annotation, default, label, depth), 12):
            trial = {**kwargs, name: sample}
            if _constructs(owner, trial):
                return trial
        return None

    def instance(self, dataclass_type: type, label: str, depth: int):
        kwargs: dict = {}
        hints = typing.get_type_hints(dataclass_type)
        for declared in fields(dataclass_type):
            if not declared.init:
                continue
            default = _field_default(declared)
            trial = self.accepted(
                dataclass_type, kwargs, declared.name, hints[declared.name], default,
                f"{label}.{declared.name}", depth,
            )
            if trial is None and default is _NO_SAMPLE:
                trial = self.accepted_required(dataclass_type, kwargs, declared, hints, label, depth)
            if trial is None:
                if default is _NO_SAMPLE:
                    return _NO_SAMPLE
                continue
            kwargs = trial
        return dataclass_type(**kwargs) if _constructs(dataclass_type, kwargs) else _NO_SAMPLE

    def accepted_required(self, dataclass_type, kwargs, declared, hints, label, depth):
        """A required field whose candidates fail only because later fields are unset."""

        for sample in itertools.islice(
            self.candidates(hints[declared.name], None, f"{label}.{declared.name}", depth), 12
        ):
            return {**kwargs, declared.name: sample}
        return None


_NO_SAMPLE = object()


def _all_subclasses(base: type) -> list[type]:
    found = []
    for child in type.__subclasses__(base):
        found.append(child)
        found.extend(_all_subclasses(child))
    return found


def _field_default(declared):
    if declared.default is not MISSING:
        return declared.default
    if declared.default_factory is not MISSING:
        return declared.default_factory()
    return _NO_SAMPLE


def _constructs(dataclass_type: type, kwargs: dict) -> bool:
    try:
        dataclass_type(**kwargs)
    except (TypeError, ValueError):
        return False
    return True


def raw(value):
    """The value as nested plain data, reading dataclass fields without resolution."""

    if is_dataclass(value) and not isinstance(value, type):
        return (
            type(value),
            {
                declared.name: raw(DataclassFieldAccess.raw_value(value, declared.name))
                for declared in fields(value)
                if declared.init
            },
        )
    if isinstance(value, FunctionStep):
        return (FunctionStep, {name: raw(vars(value)[name]) for name in STEP_PARAMETERS})
    if isinstance(value, (list, tuple)):
        return (type(value), [raw(item) for item in value])
    if isinstance(value, dict):
        return (dict, {raw(key): raw(item) for key, item in value.items()})
    return value


def load(value, clean_mode: bool):
    source = generate_python_source(Assignment("value", value), clean_mode=clean_mode)
    namespace: dict[str, object] = {}
    exec(compile(source, "<round-trip>", "exec"), namespace)
    return source, namespace["value"]


